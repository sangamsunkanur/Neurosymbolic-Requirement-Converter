def process_requirement(requirement):
    """
    Runs the complete hybrid conversion pipeline:

    1. Validate the natural-language requirement.
    2. Extract semantic structure using the LLM.
    3. Verify and repair the AST deterministically.
    4. Generate CNL deterministically.
    5. Generate temporal logic deterministically.
    6. Regenerate readable English deterministically.
    """

    if not isinstance(requirement, str):
        return {
            "success": False,
            "stage": "input",
            "error": "The requirement must be provided as text."
        }

    requirement = requirement.strip()

    if not requirement:
        return {
            "success": False,
            "stage": "input",
            "error": "The requirement cannot be empty."
        }

    # ============================================================
    # STAGE 1 — INPUT VALIDATION
    # ============================================================

    validation = validate_requirement(requirement)

    if not isinstance(validation, dict):
        return {
            "success": False,
            "stage": "validation",
            "input": requirement,
            "error": (
                "The validator returned an invalid result format."
            )
        }

    if "success" in validation:
        if not validation.get("success", False):
            return {
                "success": False,
                "stage": "validation",
                "input": requirement,
                "error": validation.get(
                    "error",
                    "Requirement validation failed."
                )
            }

        validation_data = validation.get("data", {})

    else:
        validation_data = validation

    if not isinstance(validation_data, dict):
        return {
            "success": False,
            "stage": "validation",
            "input": requirement,
            "error": (
                "The validator did not return valid validation data."
            )
        }

    validation_status = str(
        validation_data.get("status", "")
    ).strip().lower()

    if validation_status != "valid":
        return {
            "success": False,
            "stage": "validation",
            "input": requirement,
            "validation": validation_data,
            "error": (
                "The input could not be processed as a "
                "valid formalizable requirement."
            )
        }

    # ============================================================
    # STAGE 2 — SEMANTIC EXTRACTION
    # ============================================================

    semantic_result = extract_semantics(requirement)

    if not isinstance(semantic_result, dict):
        return {
            "success": False,
            "stage": "semantic_extraction",
            "input": requirement,
            "validation": validation_data,
            "error": (
                "The semantic extractor returned an invalid result."
            )
        }

    if not semantic_result.get("success", False):
        return {
            "success": False,
            "stage": "semantic_extraction",
            "input": requirement,
            "validation": validation_data,
            "error": semantic_result.get(
                "error",
                "Semantic extraction failed."
            )
        }

    semantic_data = semantic_result.get("data")

    if not isinstance(semantic_data, dict):
        return {
            "success": False,
            "stage": "semantic_extraction",
            "input": requirement,
            "validation": validation_data,
            "error": (
                "The semantic extractor did not return "
                "valid semantic data."
            )
        }

    original_semantic_data = dict(semantic_data)
    original_ast = semantic_data.get("ast")

    # ============================================================
    # STAGE 3 — SEMANTIC VERIFICATION AND REPAIR
    # ============================================================

    verification_result = verify_and_repair_semantics(
        requirement,
        semantic_data
    )

    if not isinstance(verification_result, dict):
        return {
            "success": False,
            "stage": "semantic_verification",
            "input": requirement,
            "validation": validation_data,
            "semantics": semantic_data,
            "error": (
                "The semantic verifier returned an invalid result."
            )
        }

    if not verification_result.get("success", False):
        return {
            "success": False,
            "stage": "semantic_verification",
            "input": requirement,
            "validation": validation_data,
            "semantics": semantic_data,
            "semantic_verification": verification_result,
            "error": verification_result.get(
                "error",
                "Semantic verification failed."
            )
        }

    verified_semantic_data = verification_result.get("data")

    if not isinstance(verified_semantic_data, dict):
        return {
            "success": False,
            "stage": "semantic_verification",
            "input": requirement,
            "validation": validation_data,
            "semantics": semantic_data,
            "error": (
                "The semantic verifier did not return "
                "valid verified semantic data."
            )
        }

    semantic_data = verified_semantic_data

    semantic_verification = semantic_data.get(
        "semantic_verification",
        {}
    )

    # ============================================================
    # STAGES 4–6 — DETERMINISTIC GENERATION
    # ============================================================

    try:
        cnl = generate_cnl(
            semantic_data
        )

        temporal_logic = generate_temporal_logic(
            semantic_data
        )

        english = generate_english(
            semantic_data
        )

    except Exception as error:
        return {
            "success": False,
            "stage": "deterministic_generation",
            "input": requirement,
            "validation": validation_data,
            "original_semantics": original_semantic_data,
            "semantics": semantic_data,
            "semantic_verification": semantic_verification,
            "error": str(error)
        }

    if not isinstance(temporal_logic, dict):
        return {
            "success": False,
            "stage": "deterministic_generation",
            "input": requirement,
            "validation": validation_data,
            "semantics": semantic_data,
            "error": (
                "Temporal logic generation returned "
                "an invalid result."
            )
        }

    logic_type = temporal_logic.get("logic_type")
    formula = temporal_logic.get("formula")

    if not logic_type or not formula:
        return {
            "success": False,
            "stage": "deterministic_generation",
            "input": requirement,
            "validation": validation_data,
            "semantics": semantic_data,
            "error": (
                "Temporal logic generation did not return "
                "a complete logic result."
            )
        }

    return {
        "success": True,
        "input": requirement,
        "validation": validation_data,
        "original_semantics": original_semantic_data,
        "original_ast": original_ast,
        "semantics": semantic_data,
        "verified_ast": semantic_data.get("ast"),
        "semantic_verification": semantic_verification,
        "cnl": cnl,
        "logic_type": logic_type,
        "temporal_logic": formula,
        "english": english
    }


def display_pipeline_result(result):
    """
    Displays only the final user-facing conversion result.

    Detailed AST and verification information remains stored
    inside the result dictionary for evaluation and debugging,
    but it is not printed in the interactive interface.
    """

    print("=" * 80)
    print("NEUROSYMBOLIC REQUIREMENT CONVERSION PIPELINE")
    print("=" * 80)

    if not isinstance(result, dict):
        print("STATUS: FAILED")
        print("-" * 80)
        print("ERROR:")
        print("The pipeline returned an invalid result.")
        print("=" * 80)
        return

    if not result.get("success", False):
        print("STATUS: FAILED")
        print("-" * 80)
        print("FAILED STAGE:")
        print(
            result.get(
                "stage",
                "unknown"
            )
        )
        print("-" * 80)
        print("ERROR:")
        print(
            result.get(
                "error",
                "Unknown error"
            )
        )

        validation = result.get("validation")

        if isinstance(validation, dict):
            suggestion = str(
                validation.get(
                    "suggestion",
                    ""
                )
            ).strip()

            if suggestion:
                print("-" * 80)
                print("SUGGESTION:")
                print(suggestion)

        print("=" * 80)
        return

    print("STATUS: SUCCESS")
    print("-" * 80)

    print("INPUT — NATURAL LANGUAGE:")
    print(result["input"])

    print("-" * 80)

    print("CONTROLLED NATURAL LANGUAGE:")
    print(result["cnl"])

    print("-" * 80)

    print(f'{result["logic_type"]} FORMULA:')
    print(result["temporal_logic"])

    print("-" * 80)

    print("REGENERATED ENGLISH:")
    print(result["english"])

    print("-" * 80)

    print("FINAL CONFIDENCE:")
    print(
        result["semantics"].get(
            "confidence",
            "not provided"
        )
    )

    print("=" * 80)


