def parse_negative_until_requirement(requirement):
    """
    Parses:

        subject must not action until condition
    """

    if not isinstance(requirement, str):
        return None

    match = re.match(
        (
            r"^\s*"
            r"(?P<subject>.+?)"
            r"\s+(?:must|shall)\s+not\s+"
            r"(?P<action>.+?)"
            r"\s+until\s+"
            r"(?P<condition>.+?)"
            r"[.!?]?\s*$"
        ),
        requirement,
        flags=re.IGNORECASE
    )

    if not match:
        return None

    prohibited_event = (
        match.group("subject").strip()
        + " "
        + match.group("action").strip()
    )

    enabling_condition = (
        match.group("condition").strip()
    )

    return {
        "prohibited_event": prohibited_event,
        "enabling_condition": enabling_condition
    }


def build_negative_until_ast(
    requirement,
    original_ast
):
    """
    Builds the correct AST for:

        event B must not occur until condition A

    Correct structure:

        UNTIL(
            NOT(B),
            A
        )
    """

    parsed = parse_negative_until_requirement(
        requirement
    )

    if parsed is None:
        return None

    atom_nodes = collect_atom_nodes(
        original_ast
    )

    prohibited_atom = find_best_matching_atom(
        atom_nodes,
        parsed["prohibited_event"]
    )

    condition_atom = find_best_matching_atom(
        atom_nodes,
        parsed["enabling_condition"]
    )

    if (
        prohibited_atom is None
        or condition_atom is None
    ):
        return None

    if (
        prohibited_atom.get("proposition")
        ==
        condition_atom.get("proposition")
    ):
        return None

    return {
        "operator": "UNTIL",
        "left": {
            "operator": "NOT",
            "operand": prohibited_atom
        },
        "right": condition_atom
    }


