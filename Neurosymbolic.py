import re


def _split_subject_and_action(text):
    """
    Splits a simple energy-system clause into its subject and action.

    Example:
        "the backup generator activates"
        -> ("the backup generator", "activate")
    """

    text = str(text).strip()

    verb_forms = {
        "activates": "activate",
        "activate": "activate",
        "fails": "fail",
        "fail": "fail",
        "shuts down": "shut down",
        "shut down": "shut down",
        "triggers": "trigger",
        "trigger": "trigger",
        "compensates": "compensate",
        "compensate": "compensate",
        "exceeds": "exceed",
        "exceed": "exceed",
        "reaches": "reach",
        "reach": "reach",
        "monitors": "monitor",
        "monitor": "monitor",
        "is monitored": "be monitored",
        "are monitored": "be monitored",
        "is bypassed": "be bypassed",
        "are bypassed": "be bypassed",
        "occurs": "occur",
        "occur": "occur",
        "responds": "respond",
        "respond": "respond",
        "opens": "open",
        "open": "open",
        "closes": "close",
        "close": "close",
        "starts": "start",
        "start": "start",
        "stops": "stop",
        "stop": "stop"
    }

    ordered_forms = sorted(
        verb_forms,
        key=len,
        reverse=True
    )

    pattern = r"\b(" + "|".join(
        re.escape(form)
        for form in ordered_forms
    ) + r")\b"

    match = re.search(
        pattern,
        text,
        flags=re.IGNORECASE
    )

    if not match:
        return None, text

    subject = text[:match.start()].strip()
    matched_verb = match.group(0).lower()
    remainder = text[match.end():].strip()

    action = verb_forms[matched_verb]

    if remainder:
        action = f"{action} {remainder}"

    return subject, action


def _make_modal_clause(text, modal):
    """
    Converts an atomic clause into a modal requirement clause.

    Example:
        "the backup generator activates" + "must eventually"
        -> "the backup generator must eventually activate"
    """

    subject, action = _split_subject_and_action(text)

    if subject:
        return f"{subject} {modal} {action}"

    return f"{modal} {text}"


def ast_to_cnl(node):
    """
    Converts the verified semantic AST into Controlled Natural Language.
    This stage is deterministic and does not call the LLM.
    """

    if not isinstance(node, dict):
        raise ValueError("AST node must be a dictionary.")

    operator = str(
        node.get("operator", "")
    ).strip().upper()

    if operator == "ATOM":
        text = str(
            node.get("text", "")
        ).strip()

        if not text:
            raise ValueError(
                "ATOM node is missing its text."
            )

        return text

    if operator == "NOT":
        operand = ast_to_cnl(
            node["operand"]
        )

        return f"it is not the case that {operand}"

    if operator == "AND":
        left = ast_to_cnl(
            node["left"]
        )
        right = ast_to_cnl(
            node["right"]
        )

        return f"both {left} and {right}"

    if operator == "OR":
        left = ast_to_cnl(
            node["left"]
        )
        right = ast_to_cnl(
            node["right"]
        )

        return f"either {left} or {right}"

    if operator == "IMPLIES":
        left = ast_to_cnl(
            node["left"]
        )
        right = ast_to_cnl(
            node["right"]
        )

        return f"if {left}, then {right}"

    if operator == "ALWAYS":
        operand_node = node["operand"]

        # Response pattern:
        # G(trigger -> F(response))
        if (
            isinstance(operand_node, dict)
            and str(
                operand_node.get("operator", "")
            ).strip().upper() == "IMPLIES"
            and isinstance(
                operand_node.get("right"),
                dict
            )
            and str(
                operand_node["right"].get(
                    "operator",
                    ""
                )
            ).strip().upper() == "EVENTUALLY"
        ):
            trigger = ast_to_cnl(
                operand_node["left"]
            )

            response_node = operand_node[
                "right"
            ]["operand"]

            if (
                isinstance(response_node, dict)
                and str(
                    response_node.get(
                        "operator",
                        ""
                    )
                ).strip().upper() == "ATOM"
            ):
                response = _make_modal_clause(
                    response_node.get("text", ""),
                    "must eventually"
                )

                return f"whenever {trigger}, {response}"

        operand = ast_to_cnl(
            operand_node
        )

        return f"it is always the case that {operand}"

    if operator == "EVENTUALLY":
        operand = ast_to_cnl(
            node["operand"]
        )

        return f"eventually, {operand}"

    if operator == "NEXT":
        operand = ast_to_cnl(
            node["operand"]
        )

        return f"in the next state, {operand}"

    if operator == "UNTIL":
        left_node = node["left"]
        right_node = node["right"]

        # Negative precedence pattern:
        # NOT(prohibited_event) U enabling_condition
        if (
            isinstance(left_node, dict)
            and str(
                left_node.get("operator", "")
            ).strip().upper() == "NOT"
            and isinstance(
                left_node.get("operand"),
                dict
            )
            and str(
                left_node["operand"].get(
                    "operator",
                    ""
                )
            ).strip().upper() == "ATOM"
        ):
            prohibited_text = left_node[
                "operand"
            ].get("text", "")

            prohibited_clause = _make_modal_clause(
                prohibited_text,
                "must not"
            )

            condition = ast_to_cnl(
                right_node
            )

            return (
                f"{prohibited_clause} until {condition}"
            )

        left = ast_to_cnl(
            left_node
        )
        right = ast_to_cnl(
            right_node
        )

        return f"{left} must remain true until {right}"

    if operator == "WEAK_UNTIL":
        left = ast_to_cnl(
            node["left"]
        )
        right = ast_to_cnl(
            node["right"]
        )

        return f"{left} unless and until {right}"

    if operator == "RELEASE":
        left = ast_to_cnl(
            node["left"]
        )
        right = ast_to_cnl(
            node["right"]
        )

        return f"{right} must continue unless {left} occurs"

    if operator == "WITHIN":
        operand = ast_to_cnl(
            node["operand"]
        )
        value = node.get("value")
        unit = str(
            node.get("unit", "")
        ).strip()

        if value is None or not unit:
            raise ValueError(
                "WITHIN requires both a value and a unit."
            )

        return f"within {value} {unit}, {operand}"

    raise ValueError(
        f"Unsupported CNL operator: {operator}"
    )


def generate_cnl(semantic_data):
    """
    Generates the final Controlled Natural Language sentence.
    """

    if not isinstance(semantic_data, dict):
        raise ValueError(
            "Semantic data must be a dictionary."
        )

    ast = semantic_data.get("ast")

    if not isinstance(ast, dict):
        raise ValueError(
            "Semantic data does not contain a valid AST."
        )

    cnl = ast_to_cnl(ast).strip()

    if cnl:
        cnl = cnl[0].upper() + cnl[1:]

    if not cnl.endswith("."):
        cnl += "."

    return cnl


