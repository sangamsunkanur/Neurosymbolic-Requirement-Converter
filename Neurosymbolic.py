def collect_ast_atoms(ast):
    """
    Collects all ATOM values from an AST.
    """

    if not isinstance(ast, dict):
        return []

    operator = ast.get("operator")

    if operator == "ATOM":
        return [
            {
                "text": ast.get("text"),
                "proposition": ast.get("proposition")
            }
        ]

    if operator in {
        "NOT",
        "ALWAYS",
        "EVENTUALLY"
    }:
        return collect_ast_atoms(
            ast.get("operand")
        )

    if operator in {
        "IMPLIES",
        "UNTIL",
        "AND",
        "OR"
    }:
        return (
            collect_ast_atoms(
                ast.get("left")
            )
            +
            collect_ast_atoms(
                ast.get("right")
            )
        )

    return []


def collect_atom_nodes(ast):
    """
    Collects complete ATOM nodes from an AST.
    """

    if not isinstance(ast, dict):
        return []

    operator = ast.get("operator")

    if operator == "ATOM":
        return [deepcopy(ast)]

    if operator in {
        "NOT",
        "ALWAYS",
        "EVENTUALLY"
    }:
        return collect_atom_nodes(
            ast.get("operand")
        )

    if operator in {
        "IMPLIES",
        "UNTIL",
        "AND",
        "OR"
    }:
        return (
            collect_atom_nodes(
                ast.get("left")
            )
            +
            collect_atom_nodes(
                ast.get("right")
            )
        )

    return []


def deduplicate_atoms(atoms):
    """
    Removes duplicate atoms while preserving their order.
    """

    unique_atoms = []
    seen = set()

    if not isinstance(atoms, list):
        return unique_atoms

    for atom in atoms:
        if not isinstance(atom, dict):
            continue

        proposition = atom.get("proposition")

        if (
            proposition
            and proposition not in seen
        ):
            unique_atoms.append({
                "text": atom.get("text"),
                "proposition": proposition
            })

            seen.add(proposition)

    return unique_atoms


