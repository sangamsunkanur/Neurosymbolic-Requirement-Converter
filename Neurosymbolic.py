def verify_and_repair_semantics(
    requirement,
    semantic_data
):
    """
    Validates and repairs the extracted AST using deterministic
    temporal requirement-pattern rules.

    Repair order:
        1. Negative UNTIL / precedence pattern
        2. Triggered response pattern
        3. Accept unchanged AST
    """

    if (
        not isinstance(requirement, str)
        or not requirement.strip()
    ):
        return {
            "success": False,
            "status": "needs_review",
            "error": (
                "The original requirement must be non-empty text."
            )
        }

    if not isinstance(semantic_data, dict):
        return {
            "success": False,
            "status": "needs_review",
            "error": (
                "Semantic data must be a dictionary."
            )
        }

    original_ast = semantic_data.get(
        "ast"
    )

    structure_result = validate_ast_structure(
        original_ast
    )

    if not structure_result["valid"]:
        return {
            "success": False,
            "status": "needs_review",
            "error": (
                "The extracted AST is structurally invalid."
            ),
            "details": structure_result["errors"]
        }

    # ------------------------------------------------------------
    # RULE 1 — NEGATIVE UNTIL / PRECEDENCE
    # ------------------------------------------------------------

    negative_until_ast = build_negative_until_ast(
        requirement,
        original_ast
    )

    if negative_until_ast is not None:
        repaired_structure = validate_ast_structure(
            negative_until_ast
        )

        if not repaired_structure["valid"]:
            return {
                "success": False,
                "status": "needs_review",
                "error": (
                    "The repaired UNTIL AST is structurally invalid."
                ),
                "details": repaired_structure["errors"]
            }

        if negative_until_ast != original_ast:
            return build_verified_result(
                semantic_data=semantic_data,
                ast=negative_until_ast,
                status="repaired",
                reason=(
                    "The UNTIL operands and negation were normalised. "
                    "The prohibited event is negated on the left of "
                    "UNTIL, and the enabling condition is on the right."
                ),
                verifier_confidence=0.95
            )

        return build_verified_result(
            semantic_data=semantic_data,
            ast=original_ast,
            status="accepted",
            reason=(
                "The negative UNTIL requirement already uses the "
                "correct precedence structure."
            ),
            verifier_confidence=1.0
        )

    # ------------------------------------------------------------
    # RULE 2 — TRIGGERED RESPONSE
    # ------------------------------------------------------------

    if (
        is_triggered_response_requirement(
            requirement
        )
        and is_response_ast(
            original_ast
        )
    ):
        if response_has_eventually(
            original_ast
        ):
            return build_verified_result(
                semantic_data=semantic_data,
                ast=original_ast,
                status="accepted",
                reason=(
                    "The triggered response already places "
                    "EVENTUALLY around the required response."
                ),
                verifier_confidence=1.0
            )

        repaired_response_ast = repair_response_ast(
            original_ast
        )

        repaired_structure = validate_ast_structure(
            repaired_response_ast
        )

        if not repaired_structure["valid"]:
            return {
                "success": False,
                "status": "needs_review",
                "error": (
                    "The repaired response AST is structurally invalid."
                ),
                "details": repaired_structure["errors"]
            }

        return build_verified_result(
            semantic_data=semantic_data,
            ast=repaired_response_ast,
            status="repaired",
            reason=(
                "The triggered response was normalised by placing "
                "EVENTUALLY around the required consequence."
            ),
            verifier_confidence=0.95
        )

    # ------------------------------------------------------------
    # RULE 3 — ACCEPT OTHER STRUCTURALLY VALID PATTERNS
    # ------------------------------------------------------------

    return build_verified_result(
        semantic_data=semantic_data,
        ast=original_ast,
        status="accepted",
        reason=(
            "The AST is structurally valid and no supported "
            "deterministic repair was required."
        ),
        verifier_confidence=1.0
    )


