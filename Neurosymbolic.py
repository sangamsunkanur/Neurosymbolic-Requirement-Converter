def validate_proposition_name(proposition):
    """
    Checks whether an atomic proposition uses valid snake_case.
    """

    return (
        isinstance(proposition, str)
        and bool(
            re.fullmatch(
                r"[a-z][a-z0-9_]*",
                proposition.strip()
            )
        )
    )


# Compatibility with earlier diagnostic code.
def validate_atom_id(atom_id):
    return validate_proposition_name(atom_id)


def normalise_confidence(value, default=1.0):
    """
    Converts confidence to a value between 0.0 and 1.0.
    """

    try:
        value = float(value)

    except (TypeError, ValueError):
        value = float(default)

    return max(
        0.0,
        min(1.0, value)
    )


