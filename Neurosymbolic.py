def validate_ast_structure(ast, path="ast"):
    """
    Recursively validates the AST structure.

    Returns:
        {
            "valid": bool,
            "errors": list
        }
    """

    errors = []

    if not isinstance(ast, dict):
        return {
            "valid": False,
            "errors": [
                f"{path} must be a dictionary."
            ]
        }

    operator = ast.get("operator")

    if operator not in SUPPORTED_OPERATORS:
        return {
            "valid": False,
            "errors": [
                (
                    f"{path} contains unsupported operator: "
                    f"{operator}"
                )
            ]
        }

    # ------------------------------------------------------------
    # ATOM
    # ------------------------------------------------------------

    if operator == "ATOM":
        text = ast.get("text")
        proposition = ast.get("proposition")

        if not isinstance(text, str) or not text.strip():
            errors.append(
                f"{path}.text must be non-empty text."
            )

        if not validate_proposition_name(proposition):
            errors.append(
                (
                    f"{path}.proposition must be a valid "
                    "snake_case identifier."
                )
            )

    # ------------------------------------------------------------
    # UNARY OPERATORS
    # ------------------------------------------------------------

    elif operator in {
        "NOT",
        "ALWAYS",
        "EVENTUALLY"
    }:
        if "operand" not in ast:
            errors.append(
                f"{path}.operand is required for {operator}."
            )

        else:
            child_result = validate_ast_structure(
                ast["operand"],
                f"{path}.operand"
            )

            errors.extend(
                child_result["errors"]
            )

    # ------------------------------------------------------------
    # BINARY OPERATORS
    # ------------------------------------------------------------

    elif operator in {
        "IMPLIES",
        "UNTIL",
        "AND",
        "OR"
    }:
        for side in ["left", "right"]:
            if side not in ast:
                errors.append(
                    f"{path}.{side} is required for {operator}."
                )

            else:
                child_result = validate_ast_structure(
                    ast[side],
                    f"{path}.{side}"
                )

                errors.extend(
                    child_result["errors"]
                )

    return {
        "valid": len(errors) == 0,
        "errors": errors
    }


