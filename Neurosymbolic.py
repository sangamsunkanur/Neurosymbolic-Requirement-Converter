def is_triggered_response_requirement(requirement):
    """
    Detects triggered response requirements.

    Examples:
        The generator must activate when power fails.
        If voltage drops, the battery must compensate.
        Whenever a fault occurs, an alert must be issued.
    """

    text = normalise_text(
        requirement
    )

    has_trigger = bool(
        re.search(
            r"\b(when|whenever|if|after|once)\b",
            text
        )
    )

    has_obligation = bool(
        re.search(
            r"\b(must|shall|required|has to)\b",
            text
        )
    )

    # Prevent UNTIL requirements from being treated as responses.
    has_until = bool(
        re.search(
            r"\buntil\b",
            text
        )
    )

    return (
        has_trigger
        and has_obligation
        and not has_until
    )


def is_response_ast(ast):
    """
    Checks for ALWAYS(IMPLIES(trigger, response)).
    """

    return (
        isinstance(ast, dict)
        and ast.get("operator") == "ALWAYS"
        and isinstance(ast.get("operand"), dict)
        and ast["operand"].get("operator") == "IMPLIES"
    )


def response_has_eventually(ast):
    """
    Checks whether the response is already EVENTUALLY(response).
    """

    if not is_response_ast(ast):
        return False

    response = ast["operand"].get(
        "right"
    )

    return (
        isinstance(response, dict)
        and response.get("operator") == "EVENTUALLY"
    )


def repair_response_ast(ast):
    """
    Converts:

        ALWAYS(IMPLIES(trigger, response))

    into:

        ALWAYS(IMPLIES(trigger, EVENTUALLY(response)))
    """

    repaired_ast = deepcopy(ast)

    response = repaired_ast[
        "operand"
    ]["right"]

    repaired_ast[
        "operand"
    ]["right"] = {
        "operator": "EVENTUALLY",
        "operand": response
    }

    return repaired_ast


