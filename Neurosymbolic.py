def normalise_text(text):
    """
    Normalises text for atom matching.
    """

    if not isinstance(text, str):
        return ""

    text = text.lower()

    text = re.sub(
        r"[^a-z0-9\s]",
        " ",
        text
    )

    text = re.sub(
        r"\s+",
        " ",
        text
    )

    return text.strip()


def get_matching_tokens(text):
    """
    Removes grammatical words and keeps semantic keywords.
    """

    stop_words = {
        "the",
        "a",
        "an",
        "is",
        "are",
        "was",
        "were",
        "be",
        "been",
        "being",
        "must",
        "shall",
        "should",
        "not",
        "until",
        "when",
        "whenever",
        "if",
        "after",
        "once",
        "then",
        "that",
        "it",
        "to",
        "of",
        "in",
        "on",
        "at"
    }

    return {
        token
        for token in normalise_text(text).split()
        if token not in stop_words
    }


def find_best_matching_atom(atom_nodes, phrase):
    """
    Finds the atom that best matches a phrase from the requirement.
    """

    phrase_tokens = get_matching_tokens(
        phrase
    )

    if not phrase_tokens:
        return None

    best_atom = None
    best_score = 0

    for atom in atom_nodes:
        atom_tokens = get_matching_tokens(
            atom.get("text", "")
        )

        overlap = len(
            phrase_tokens.intersection(
                atom_tokens
            )
        )

        if overlap > best_score:
            best_score = overlap
            best_atom = atom

    if best_score == 0:
        return None

    return deepcopy(best_atom)


